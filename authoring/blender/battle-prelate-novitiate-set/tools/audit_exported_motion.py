def _import_without_bone_displays(path):
    imported=_IMPORT_GLB(path)
    displays={bone.custom_shape for obj in imported if obj.type=="ARMATURE" for bone in obj.pose.bones if bone.custom_shape}
    for obj in displays & imported:
        # These are generated by Blender's importer, absent from the GLB mesh
        # list, and referenced only as armature UI display shapes.
        obj.hide_render=True
        obj.hide_set(True)
        _IGNORED_BONE_DISPLAYS.append({"source":path.name,"object":obj.name,"reason":"Armature bone custom_shape display"})
    return imported-displays


