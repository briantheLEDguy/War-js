"""Serialize individually authored leg armor cages and explicit face records."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = []


def part(name, points, faces, material="steel", bone="shin_L", modifiers=None,
         closed=False, slot="legs", creases=(), instances=()):
    rows = [line.split() for line in points.strip().splitlines() if line.strip()]
    data = {"id": name, "slot": slot, "rigid_bone": bone,
            "mirror_bone": bone.replace("_L", "_R"),
            "vertices": [{"id": f"v{i:03}", "co": [float(v) for v in r[:3]]}
                         for i, r in enumerate(rows)], "faces": [],
            "modifiers": ([] if instances else [{"type": "MIRROR", "axis": "X"}]) + (modifiers or []),
            "landmarks": {}, "seams": [], "sharp_edges": [],
            "creases": [{"edge": [f"v{a:03}", f"v{b:03}"], "value": value}
                        for a, b, value in creases], "closed": closed,
            "transform": {"location": [0, 0, 0], "rotation_degrees": [0, 0, 0],
                          "scale": [1, 1, 1]}}
    for index, line in enumerate(faces.strip().splitlines()):
        indices = [int(v) for v in line.split()]
        data["faces"].append({"id": f"f{index:03}",
            "vertices": [f"v{i:03}" for i in indices],
            "uv": [[float(v) for v in rows[i][3:5]] for i in indices],
            "material": material})
    if instances:
        data["instances"] = [{"location": list(pos), "rotation_degrees": list(rot),
                              "scale": [1, 1, 1]} for pos, rot in instances]
    PARTS.append(data)
    return data


