def part(name, points, faces, material, closed=False, modifiers=None, instances=None, landmarks=None):
    rows = [row.split() for row in points.strip().splitlines() if row.strip()]
    result = {
        "id": name, "slot": "weapon", "rigid_bone": "weapon_root",
        "vertices": [{"id": f"v{i:03}", "co": [float(x) for x in row[:3]]} for i, row in enumerate(rows)],
        "faces": [{"id": f"f{i:03}", "vertices": [f"v{int(v):03}" for v in row.split()],
                   "uv": [[float(x) for x in rows[int(v)][3:5]] for v in row.split()], "material": material}
                  for i, row in enumerate(faces.strip().splitlines()) if row.strip()],
        "modifiers": modifiers or [], "landmarks": landmarks or {}, "seams": [], "sharp_edges": [],
        "creases": [], "closed": closed,
        "transform": {"location": [0, 0, 0], "rotation_degrees": [0, 0, 0], "scale": [1, 1, 1]},
    }
    if instances:
        result["instances"] = instances
    PARTS.append(result)
    return result


