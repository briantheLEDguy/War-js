def make_profile_actions(profile: str) -> dict:
    """Return the standard clip set with career-specific keyframe overrides."""
    actions = deepcopy(ACTIONS)
    overrides = PROFILE_OVERRIDES.get(profile, {})
    for action_name, action_patch in overrides.items():
        if action_name not in actions:
            continue
        patched = actions[action_name]
        if "duration_frames" in action_patch:
            patched["duration_frames"] = action_patch["duration_frames"]
        if "loop" in action_patch:
            patched["loop"] = action_patch["loop"]
        if "keyframes" in action_patch:
            patched["keyframes"].update(action_patch["keyframes"])
    return actions


